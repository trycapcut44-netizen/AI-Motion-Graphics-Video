import os
import uuid
import edge_tts
from pathlib import Path
from typing import Optional
from app.config import settings
from app.providers.base import BaseTTSProvider


class EdgeTTSProvider(BaseTTSProvider):
    def __init__(self):
        self.default_voice = "hi-IN-SwaraNeural"

    def _format_rate(self, speed: float) -> str:
        pct = int(round((speed - 1.0) * 100))
        if pct >= 0:
            return f"+{pct}%"
        return f"{pct}%"

    def _format_pitch(self, pitch: float) -> str:
        pct = int(round((pitch - 1.0) * 100))
        if pct >= 0:
            return f"+{pct}Hz"
        return f"{pct}Hz"

    async def synthesize(
        self,
        text: str,
        voice_id: str,
        language_code: str,
        speed: float = 1.0,
        pitch: float = 1.0,
        output_path: Optional[Path] = None
    ) -> Path:
        if not output_path:
            output_path = settings.TEMP_DIR / f"tts_{uuid.uuid4().hex}.mp3"
        
        # Guard against empty or symbol-only text
        clean_text = (text or "").strip()
        has_words = any(c.isalnum() for c in clean_text)
        if not has_words:
            from app.services.speech_sync import SpeechSynchronizer
            sync = SpeechSynchronizer()
            sync.generate_silence(1.0, output_path)
            return output_path

        rate_str = self._format_rate(speed)
        pitch_str = self._format_pitch(pitch)
        
        # Verify if voice_id is valid or fallback
        chosen_voice = voice_id if voice_id else self.default_voice

        try:
            communicate = edge_tts.Communicate(
                clean_text,
                voice=chosen_voice,
                rate=rate_str,
                pitch=pitch_str
            )
            await communicate.save(str(output_path))
            if not output_path.exists() or output_path.stat().st_size == 0:
                raise RuntimeError("Empty audio generated by TTS.")
        except Exception as e:
            print(f"[EdgeTTS] Warning: TTS generation fallback for '{clean_text[:20]}': {e}")
            from app.services.speech_sync import SpeechSynchronizer
            sync = SpeechSynchronizer()
            sync.generate_silence(2.0, output_path)

        return output_path
